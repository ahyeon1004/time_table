export function thirdGradeTeacher(name, classroom, day, period) {
  const key = name
    .replace(/\[보강\]/g, "")
    .replace(/^\s*\*\s*/, "")
    .replace(/\s+/g, "");
  // 사용자가 정정한 3학년 1반 과목별 담당. 기존 참고 표보다 우선한다.
  if (String(classroom) === "1") {
    if (key === "프로그래밍언어응용") return "최병준";
    if (key === "애플리케이션배포") return "김미영";
  }
  if (isUnconfirmedTeacher(name, classroom)) return "이세준";
  const subject = SUBJECTS[key];
  if (!subject) return null;
  const lessons = (REFERENCE[String(classroom)] ?? []).filter(
    (row) => row[2] === subject,
  );
  const slot = lessons.find((row) => row[0] === day && row[1] === period);
  const candidates = [...new Set(lessons.map((row) => row[3]))];
  const short = slot?.[3] ?? (candidates.length === 1 ? candidates[0] : null);
  return short ? (FULL_NAMES[short] ?? short) : null;
}

export function isUnconfirmedTeacher(name, classroom) {
  return (
    String(classroom) === "4" &&
    name.includes("[보강]") &&
    name
      .replace(/\[보강\]/g, "")
      .replace(/^\s*\*\s*/, "")
      .replace(/\s+/g, "") === "로봇센서인터페이스개발"
  );
}
